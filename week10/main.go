// ダウンロード処理を行う関数
func download(w http.ResponseWriter, r *http.Request) {
	// 1. POSTメソッド以外を弾く（セキュリティ向上）
	if r.Method != http.MethodPost {
		http.Error(w, "Method Not Allowed", http.StatusMethodNotAllowed)
		return
	}

	// 2. フォームデータの解析
	if err := r.ParseForm(); err != nil {
		http.Error(w, "Bad Request", http.StatusBadRequest)
		return
	}

	name := r.FormValue("filename")
	typ := r.FormValue("type")
	text := r.FormValue("text")

	// ファイル名が空の場合はデフォルト名を設定
	if name == "" {
		name = "memo"
	}

	// 3. 各形式に合わせたデータ加工
	var content string
	var contentType string = "application/octet-stream; charset=utf-8"

	switch typ {
	case "txt":
		content = text
	case "csv":
		// Excelで開きやすいよう、ダブルクォートでエスケープ
		content = `"` + strings.ReplaceAll(text, `"`, `""`) + `"`
	case "dat":
		// データ形式としてヘッダーを付与
		content = "--- DATA FILE ---\n" + text
	case "html":
		// ブラウザで直接開いても文字化けしないHTML構造
		content = "<!DOCTYPE html><html><head><meta charset='utf-8'></head><body><pre>" + text + "</pre></body></html>"
		contentType = "text/html; charset=utf-8"
	case "cs":
		// C#ソースコード形式に整える
		content = fmt.Sprintf("/* Generated by Go App */\nusing System;\n\npublic class Memo {\n    public static void Main() {\n        Console.WriteLine(@\"%s\");\n    }\n}", strings.ReplaceAll(text, `"`, `""`))
	default:
		// 想定外の形式に対するエラー処理
		http.Error(w, "Invalid Format", http.StatusBadRequest)
		return
	}

	// 4. ダウンロード用ヘッダーの設定
	filename := fmt.Sprintf("%s.%s", name, typ)
	w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="%s"`, filename))
	w.Header().Set("Content-Type", contentType)


	bom := []byte{0xEF, 0xBB, 0xBF}
	if _, err := w.Write(bom); err != nil {
		fmt.Printf("BOM Error: %v\n", err)
		return
	}

	// 6. メモ本体の書き込み
	if _, err := w.Write([]byte(content)); err != nil {
		fmt.Printf("Write Error: %v\n", err)
	}
}
