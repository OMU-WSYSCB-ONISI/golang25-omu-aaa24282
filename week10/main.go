package main

import (
	"fmt"
	"net/http"
	"strings"
)

func main() {
	// ルーティング設定
	http.HandleFunc("/", memo)
	http.HandleFunc("/download", download)

	fmt.Println("Server running at http://localhost:8080")
	// サーバー起動とエラーハンドリング
	if err := http.ListenAndServe(":8080", nil); err != nil {
		fmt.Printf("Server failed to start: %v\n", err)
	}
}

